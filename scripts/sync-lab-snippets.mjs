// Regenerates the "Copy code" strings in src/app/lab/specs.ts from the real
// source files, so what a visitor copies is exactly what runs on the site.
//
//   npm run lab:snippets             rewrite the *_CODE exports
//   npm run lab:snippets -- --check  exit 1 if any of them has drifted

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8").replace(/\r\n/g, "\n");

const SNIPPETS = {
  DRAG_REVEAL_CODE: () => read("src/app/lab/dragReveal.ts"),
  RAIL_CODE: () =>
    "// ===== src/app/lab/rail.tsx =====\n\n" +
    read("src/app/lab/rail.tsx") +
    "\n/* ===== src/app/lab/rail.module.css ===== */\n\n" +
    read("src/app/lab/rail.module.css"),
  TOPBAR_CODE: () =>
    "// ===== src/app/lab/topbar.tsx =====\n\n" +
    read("src/app/lab/topbar.tsx") +
    "\n/* ===== src/app/lab/topbar.module.css ===== */\n\n" +
    read("src/app/lab/topbar.module.css"),
};

// Template-literal body: backslashes, backticks and ${ are the only hazards.
const literal = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const specsPath = path.join(root, "src/app/lab/specs.ts");
const specs = read("src/app/lab/specs.ts");
const check = process.argv.includes("--check");

let next = specs;
const drifted = [];
for (const [name, build] of Object.entries(SNIPPETS)) {
  const statement = `export const ${name} = \`${literal(build())}\`;`;
  const re = new RegExp(`export const ${name} = \`(?:\\\\[\\s\\S]|[^\`\\\\])*\`;`);
  const current = next.match(re)?.[0];
  if (current === statement) continue;
  drifted.push(name);
  next = current
    ? next.replace(current, () => statement)
    : next.trimEnd() + "\n\n// Verbatim copy of the source, generated by scripts/sync-lab-snippets.mjs.\n" + statement + "\n";
}

if (check) {
  if (drifted.length) {
    console.error("Out of date: " + drifted.join(", ") + ". Run `npm run lab:snippets`.");
    process.exit(1);
  }
  console.log("Lab snippets in sync.");
} else {
  if (drifted.length) fs.writeFileSync(specsPath, next);
  console.log(drifted.length ? "Updated: " + drifted.join(", ") : "Lab snippets already in sync.");
}
